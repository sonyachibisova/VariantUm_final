type GradeGroup = '1-4' | '5-6' | '7-8' | '9' | '10-11';

function gradeGroup(grade: number | null): GradeGroup | null {
  if (!grade) return null;
  if (grade <= 4) return '1-4';
  if (grade <= 6) return '5-6';
  if (grade <= 8) return '7-8';
  if (grade === 9) return '9';
  return '10-11';
}

